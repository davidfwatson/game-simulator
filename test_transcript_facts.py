def episode(number):
    return json.loads((OUTPUT_DIR / f'episode_{number:03d}.json').read_text())


def ledger(number):
    return json.loads((LEDGER_DIR / f'episode_{number:03d}.json').read_text())


class SayEverything(NarrativeRenderer):
    """Every optional sentence said, so a test sees what a fact enables."""

    def _optional(self, name):
        super()._optional(name)
        return True


def play_text(renderer, text, index):
    lines = text.splitlines()
    low, high = renderer._play_line_map[index]
    return '\n'.join(line for line in lines[low:high] if not line.startswith('[TTS'))


def call_of(text):
    """The words after the last delivery cue: the ball in play's call."""
    return text.rsplit('...', 1)[-1]


class TestBattedBallClaims(unittest.TestCase):
    def test_claims_need_their_fact(self):
        self.assertEqual(template_claims('Ripped into the gap, and that will roll all the way to the wall.'),
                         {'hard', 'gap', 'wall'})
        wall = supported_claims({'depth': 'wall', 'lane': 'left_line'}, 'Double')
        self.assertTrue({'deep', 'wall', 'corner', 'line'} <= wall)
        self.assertNotIn('gap', wall)
        self.assertEqual(supported_claims({'trajectory': 'fly_ball'}, 'Single'), set())
        self.assertIn('wall', supported_claims({}, 'Home Run'))
        self.assertIn('soft', supported_claims({'categoryOverride': 'bloop'}, 'Single'))
        self.assertIn('ground_path', supported_claims({'trajectory': 'ground_ball'}, 'Single'))
        templates = ['Lined {direction}. That one drops in.', 'Hard liner {direction}.', 'Lined into shallow {direction_noun}.']
        self.assertEqual(gate_templates(templates, set()), templates[:1])
        self.assertEqual(gate_templates(templates, {'hard'}), templates[:2])

    def test_directions_follow_depth_and_lane(self):
        self.assertEqual(spot_direction({'lane': 'left_line', 'trajectory': 'line_drive'}, 'Double', 'to left field', 'left field'),
                         ('down the left field line', 'left field'))
        self.assertEqual(spot_direction({'lane': 'right_line', 'trajectory': 'ground_ball'}, 'Single', 'to first', 'first'),
                         ('down the first base line', 'right field'))
        self.assertEqual(spot_direction({'lane': 'right_center', 'depth': 'deep'}, 'Flyout', 'to center field', 'center field'),
                         ('to deep right center', 'right center'))
        self.assertEqual(spot_direction({'depth': 'shallow', 'trajectory': 'fly_ball'}, 'Single', 'to left field', 'left field'),
                         ('into shallow left', 'left'))
        self.assertEqual(spot_direction({'lane': 'middle', 'trajectory': 'ground_ball'}, 'Single', 'to second', 'second'),
                         ('up the middle', 'center field'))
        self.assertEqual(spot_direction({}, 'Single', 'to left field', 'left field'), ('to left field', 'left field'))

    def test_strict_broadcasts_claim_no_unrecorded_wall_track_or_hard_contact(self):
        """Over all 17 fitted broadcasts, a wall, warning track or hard hit is
        said about a ball only when its facts record it."""
        checked = 0
        for path in sorted(OUTPUT_DIR.glob('episode_*.json')):
            data = json.loads(path.read_text())
            renderer = NarrativeRenderer(data)
            text = renderer.render()
            for index, play in enumerate(data['liveData']['plays']['allPlays']):
                hit = next((event.get('hitData', {}) for event in play['playEvents']
                            if event.get('details', {}).get('code') == 'X'), None)
                if hit is None or play['result']['event'] == 'Home Run':
                    continue
                call = call_of(play_text(renderer, text, index))
                supported = supported_claims(hit, play['result']['event'])
                with self.subTest(episode=path.stem, play=index):
                    if 'wall' not in supported:
                        self.assertNotRegex(call, r'\bwall\b')
                    if 'warning_track' not in supported:
                        self.assertNotIn('warning track', call)
                    if 'hard' not in supported:
                        self.assertNotRegex(call, r'\bHard grounder\b|\bHammered\b')
                    checked += 1
        self.assertGreater(checked, 600)

    def test_recorded_facts_are_narrated(self):
        renderer = NarrativeRenderer(episode(49))
        text = renderer.render()
        plays = episode(49)['liveData']['plays']['allPlays']
        ground_rule = next(i for i, play in enumerate(plays)
                           if any(e.get('hitData', {}).get('categoryOverride') == 'ground_rule' for e in play['playEvents']))
        self.assertIn('ground-rule double', play_text(renderer, text, ground_rule))
        track = [i for i, play in enumerate(plays) if play['result']['event'] == 'Flyout'
                 and any(e.get('hitData', {}).get('depth') == 'warning_track' for e in play['playEvents'])]
        self.assertTrue(track)
        self.assertTrue(any('warning track' in play_text(renderer, text, i) for i in track))


class TestRealFeedSpots(unittest.TestCase):
    """Real StatsAPI balls carry coordinates and distance, not depth/lane."""

    def test_depth_and_lane_derived_from_coordinates_like_the_simulator(self):
        from renderers.narrative.batted_ball import with_derived_spot
        # A real feed's warning-track catch in left center and a grounder up the middle.
        caught = {'launchSpeed': 103.6, 'launchAngle': 32, 'totalDistance': 365, 'trajectory': 'fly_ball',
                  'hardness': 'hard', 'location': '8', 'coordinates': {'coordX': 82.0, 'coordY': 57.0}}
        derived = with_derived_spot(caught, 'Flyout')
        self.assertEqual((derived['depth'], derived['lane']), ('warning_track', 'left_center'))
        dx, dy = (82.0 - 125.42) * 2.495, (198.27 - 57.0) * 2.495
        import math
        self.assertEqual({k: derived[k] for k in ('depth', 'lane')},
                         fieldsim.spot_facts(math.degrees(math.atan2(dx, dy)), 365, 'fly_ball', 'Flyout', True,
                                             math.hypot(dx, dy)))
        grounder = {'trajectory': 'ground_ball', 'hardness': 'hard', 'totalDistance': 6,
                    'coordinates': {'coordX': 126.0, 'coordY': 140.0}}
        self.assertEqual(with_derived_spot(grounder, 'Single')['lane'], 'middle')
        # Explicit fields win, including the simulator's "nothing notable".
        self.assertEqual(with_derived_spot({**caught, 'depth': None, 'lane': None}, 'Flyout')['depth'], None)
        self.assertEqual(with_derived_spot({**caught, 'depth': 'shallow'}, 'Flyout')['depth'], 'shallow')
        self.assertNotIn('depth', with_derived_spot({'trajectory': 'fly_ball'}, 'Flyout'))

    def test_anonymized_real_feed_keeps_location_phrasing(self):
        from blind_judge import real_game, render
        data = real_game('real_gameday.json', 7)
        hits = [event['hitData'] for play in data['liveData']['plays']['allPlays']
                for event in play['playEvents'] if 'hitData' in event]
        self.assertTrue(all('coordinates' in hit for hit in hits if hit.get('trajectory')))
        calls = [line.rsplit('...', 1)[-1] for line in render(data, 7).splitlines() if '...' in line]
        spots = [call for call in calls if 'foul' not in call and re.search(
            r'\b(?:gap|left center|right center|line|corner|wall|warning track|deep|shallow|up the middle)\b', call)]
        self.assertGreaterEqual(len(spots), 15)


