"""Game facts the hosts say that a feed can record, and how they are narrated.

Batted-ball depth, lane and hardness; runners who score or take third; the
runs a hit or home run drove in; a starter's season record; pinch hitters.
Each is recorded in the fixture (never as transcript text), narrated only
when recorded, and generated by the simulator where its field model knows it.
"""
