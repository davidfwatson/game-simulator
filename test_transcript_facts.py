class TestSimulatorFacts(unittest.TestCase):
    def ball(self, **kwargs):
        values = dict(outcome='Double', fielder='LF', trajectory='line_drive', location='LF', spray=-40.0,
                      landing=(0, 0), distance=300.0, release_point=fieldsim.polar(fieldsim.fence_distance(-40.0) - 2, -40.0))
        values.update(kwargs)
        return fieldsim.BattedBall(**values)

    def test_spot_from_the_field_model(self):
        self.assertEqual(fieldsim.spot(self.ball()), {'depth': 'wall', 'lane': 'left_line'})
        caught = self.ball(outcome='Flyout', caught=True, spray=12.0, distance=fieldsim.fence_distance(12.0) - 10,
                           trajectory='fly_ball', release_point=None)
        self.assertEqual(fieldsim.spot(caught), {'depth': 'warning_track', 'lane': 'right_center'})
        bloop = self.ball(outcome='Single', spray=3.0, distance=180.0, release_point=fieldsim.polar(190.0, 3.0))
        self.assertEqual(fieldsim.spot(bloop), {'depth': 'shallow'})
        grounder = self.ball(outcome='Single', trajectory='ground_ball', spray=2.0, distance=150.0)
        self.assertEqual(fieldsim.spot(grounder), {'lane': 'middle'})
        self.assertEqual(fieldsim.hardness(101.0), 'hard')
        self.assertEqual(fieldsim.hardness(70.0), 'soft')

    def test_simulated_balls_in_play_carry_the_facts(self):
        from baseball import BaseballSimulator
        from example_games import EXAMPLE_GAMES
        game = EXAMPLE_GAMES[0]
        simulator = BaseballSimulator(game.team1, game.team2, game_seed=game.game_seed)
        simulator.play_game()
        hits = [event['hitData'] for play in simulator.gameday_data['liveData']['plays']['allPlays']
                for event in play['playEvents'] if 'hitData' in event and 'launchSpeed' in event['hitData']]
        self.assertTrue(hits)
        self.assertTrue(all(hit['hardness'] in ('soft', 'medium', 'hard') for hit in hits))
        self.assertTrue(any(hit.get('depth') for hit in hits))
        self.assertTrue(any(hit.get('lane') for hit in hits))


class TestAnnotation(unittest.TestCase):
    def test_words_to_facts(self):
        self.assertEqual(facts_from_words('Hard grounder up the middle, and that one gets through.', 'Single', 'CF', 'ground_ball'),
                         {'lane': 'middle', 'hardness': 'hard'})
        self.assertEqual(facts_from_words('Hit in the air to deep right center. And he makes the catch on the warning track.',
                                          'Flyout', 'CF', 'fly_ball'),
                         {'depth': 'warning_track', 'lane': 'right_center'})
        self.assertEqual(facts_from_words('Looper into shallow left, and that one falls into the gap.', 'Single', 'LF', 'fly_ball'),
                         {'depth': 'shallow', 'lane': 'left_center', 'hardness': 'soft'})
        # "Over the wall" is not where the ball came to rest.
        self.assertEqual(facts_from_words('Driven down the left field line. It will bounce over the wall.', 'Double', 'LF', 'line_drive'),
                         {'lane': 'left_line'})
        # Shallow and deep together are contradictory: nothing is recorded.
        self.assertNotIn('depth', facts_from_words('Shallow center, no, deep center.', 'Flyout', 'CF', 'fly_ball'))
        self.assertEqual(facts_from_words('A ground-rule double.', 'Double', 'LF', 'line_drive')['categoryOverride'], 'ground_rule')

    def test_ledgers_and_references_record_the_facts(self):
        counts = {'depth': 0, 'lane': 0, 'hardness': 0}
        for path in LEDGER_DIR.glob('episode_*.json'):
            for play in json.loads(path.read_text())['plays']:
                for key in counts:
                    counts[key] += key in play.get('hit', {})
        self.assertGreater(counts['depth'], 150)
        self.assertGreater(counts['lane'], 100)
        self.assertGreater(counts['hardness'], 120)
        substitutions = sum('substitution' in play for path in LEDGER_DIR.glob('episode_*.json')
                            for play in json.loads(path.read_text())['plays'])
        self.assertEqual(substitutions, 26)
        stats = sum(len(json.loads(path.read_text())['game'].get('season_stats', {}))
                    for path in LEDGER_DIR.glob('episode_*.json'))
        self.assertEqual(stats, 26)


