class TestPinchHitters(unittest.TestCase):
    def test_compiled_as_an_offensive_substitution_and_said_in_the_intro(self):
        data = episode(49)
        plays = data['liveData']['plays']['allPlays']
        index = next(i for i, play in enumerate(plays) if play['matchup']['batter']['fullName'] == 'Royce Babcock')
        action = plays[index]['playEvents'][0]
        self.assertEqual(action['details']['eventType'], 'offensive_substitution')
        self.assertTrue(action['isSubstitution'])
        self.assertEqual(data['gameData']['players'][f"ID{action['replacedPlayer']['id']}"]['fullName'], 'Brocktune Shemper')
        renderer = NarrativeRenderer(data)
        text = play_text(renderer, renderer.render(), index)
        self.assertRegex(text, r'pinch[- ]hit')
        self.assertNotIn('Offensive Substitution', text)
        lines = renderer.render().splitlines()
        low, high = renderer._play_line_map[index]
        markers = [line for line in lines[low:high] if line.startswith('[TTS')]
        self.assertEqual(markers[:2], ['[TTS SPLIT HERE DELAY:11.5s]', '[TTS SPLIT HERE DELAY:9.5s]'])

    def test_replaced_man_and_slot_only_when_recorded(self):
        record = ledger(49)
        play = next(play for play in record['plays'] if play['batter'] == 'Royce Babcock')
        play['substitution'] = {'type': 'pinch_hitter'}
        data = compile_game(record, (SOURCE_DIR / record['source_file']).read_bytes())
        for draw in range(6):
            for item in data['liveData']['plays']['allPlays']:
                if item['matchup']['batter']['fullName'] == 'Royce Babcock':
                    item.setdefault('commentaryRng', {})['play_start'] = {'flow': [draw] * 12}
            text = NarrativeRenderer(copy.deepcopy(data)).render()
            intro = next(line for line in text.splitlines() if 'Babcock' in line and 'pinch' in line)
            self.assertNotIn('Shemper', intro)
            self.assertNotIn('spot', intro)


